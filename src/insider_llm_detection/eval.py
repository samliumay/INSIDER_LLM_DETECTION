"""`ild eval` — regenerate results/tables.md from run dirs.

Aggregate numbers in README/EXPERIMENTS/paper must come from this file, never from hand
reads (audit 2026-09-01 M8). Old runs lack newer meta keys; missing fields render as "?"
— eval never crashes on absent keys.
"""
import json, time
from collections import Counter
from pathlib import Path

from .run import ROOT, git_hash

RESULTS = (ROOT / "../results").resolve()

def load_run(d: Path) -> tuple[dict, list[dict]]:
    meta, eps = {}, []
    try: meta = json.loads((d / "meta.json").read_text())
    except Exception: pass
    try:
        eps = [json.loads(l) for l in (d / "episodes.jsonl").read_text().splitlines() if l.strip()]
    except Exception: pass
    return meta, eps

def _short(s: str | None, n: int = 12) -> str:
    return s[:n] if s else "?"

def _reportable(meta: dict) -> str:
    r = meta.get("reportable")
    return {True: "yes", False: "no"}.get(r, "?")

def cmd_eval(runs: list[Path] | None = None, out: Path | None = None):
    if runs is None:
        runs = [d for d in sorted(RESULTS.iterdir()) if d.is_dir()
                and ((d / "meta.json").exists() or (d / "episodes.jsonl").exists())] if RESULTS.exists() else []
    out = out or RESULTS / "tables.md"
    loaded = [(d.name, *load_run(d)) for d in runs]

    L = ["# Results tables", "",
         "GENERATED by `ild eval` — do not edit. Regenerate with `make eval`.", "",
         f"Generated: {time.strftime('%Y-%m-%dT%H:%M:%S')} | code: `{git_hash()}`", ""]

    # (a) per-run table
    L += ["## Per-run", "",
          "| run | model | dataset_version | prompt_set | reportable | episodes | `logged` counts | labelled/unlabelled | harmful by variant |",
          "|-----|-------|-----------------|------------|------------|----------|-----------------|---------------------|--------------------|"]
    for name, meta, eps in loaded:
        model = meta.get("model") or (meta.get("config") or {}).get("model") or "?"
        logged = Counter(str(e.get("logged", "?")) for e in eps)
        logged_s = ", ".join(f"{k}:{v}" for k, v in sorted(logged.items())) or "—"
        n_lab = sum(1 for e in eps if e.get("harmful") is not None)
        harm = Counter(e.get("prompt_variant", "?") for e in eps if e.get("harmful") is True)
        harm_s = ", ".join(f"{k}:{v}" for k, v in sorted(harm.items())) or ("0" if n_lab else "—")
        L.append(f"| {name} | {model} | {_short(meta.get('dataset_version'))} | "
                 f"{_short(meta.get('prompt_set_sha256'))} | {_reportable(meta)} | {len(eps)} | "
                 f"{logged_s} | {n_lab}/{len(eps) - n_lab} | {harm_s} |")
    L.append("")

    # (b) scenario × prompt_variant harm rate — reportable, labelled runs only;
    # no_answer episodes are excluded from denominators (evaluation plan §4)
    cells: dict[tuple[str, str], list[int]] = {}
    unlabelled = []
    for name, meta, eps in loaded:
        if meta.get("reportable") is not True:
            continue
        labelled = [e for e in eps if e.get("harmful") is not None]
        if not labelled:
            unlabelled.append(name); continue
        for e in labelled:
            if e.get("logged") == "no_answer":
                continue
            c = cells.setdefault((str(e.get("scenario", "?")), str(e.get("prompt_variant", "?"))), [0, 0])
            c[1] += 1; c[0] += 1 if e.get("harmful") else 0
    scenarios = sorted({s for s, _ in cells}); pvariants = sorted({v for _, v in cells})
    L += ["## Harm rate by scenario × prompt_variant",
          "(reportable, labelled runs only; `no_answer` excluded; cell = harmful/n)", ""]
    if cells:
        L.append("| scenario | " + " | ".join(pvariants) + " |")
        L.append("|" + "---|" * (len(pvariants) + 1))
        for s in scenarios:
            row = []
            for v in pvariants:
                h, n = cells.get((s, v), [0, 0])
                row.append(f"{h}/{n} ({100 * h / n:.0f}%)" if n else "—")
            L.append(f"| {s} | " + " | ".join(row) + " |")
    else:
        L.append("_No labelled reportable runs yet — `harmful` is null everywhere until `ild classify` has run._")
    L.append("")
    if unlabelled:
        L += ["Reportable but unlabelled runs (excluded from harm rates):", ""]
        L += [f"- {n}" for n in unlabelled]; L.append("")

    # (c) excluded non-reportable runs, with the reason from meta
    excluded = [(name, meta.get("reportable_note")
                 or ("reportable: false" if meta.get("reportable") is False else "no reportable flag (pre-audit run)"))
                for name, meta, _ in loaded if meta.get("reportable") is not True]
    L += ["## Excluded non-reportable runs", ""]
    L += ([f"- {n} — {reason}" for n, reason in excluded]
          or ["_None._"])
    L.append("")

    out.write_text("\n".join(L))
    print(f"wrote {out}: {len(loaded)} runs, {len(excluded)} non-reportable, {len(unlabelled)} reportable-but-unlabelled")
